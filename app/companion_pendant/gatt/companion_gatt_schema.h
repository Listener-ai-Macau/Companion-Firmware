#define COMPANION_COUNT_SERVICE(uuid, records, count, chars) + 1u
#define COMPANION_COUNT_ATTRIBUTE(id, uuid, size, props, events, variable) \
    + (2u + (((props) & 0x01u) != 0u) + (((props) & 0x30u) != 0u) + (((props) & 0x80u) != 0u))
#define COMPANION_SERVICE_ATTRIBUTES(uuid, records, count, chars) \
    + (0u chars##_SCHEMA(COMPANION_COUNT_ATTRIBUTE))
#define COMPANION_GATT_PRODUCT_SERVICE_COUNT \
    (0u COMPANION_GATT_SERVICE_SCHEMA(COMPANION_COUNT_SERVICE))
#define COMPANION_GATT_PRODUCT_ATTRIBUTE_COUNT \
    (0u COMPANION_GATT_SERVICE_SCHEMA(COMPANION_SERVICE_ATTRIBUTES))

/* Keep the existing service handle reservations, including the unused
 * e-paper slot. The service declaration itself belongs to the service pool. */
#define COMPANION_SERVICE_ATTRIBUTE_RESERVATION(uuid, records, count, chars) \
    + ((records) - 1u)
#define COMPANION_GATT_PRODUCT_ATTRIBUTE_RESERVATION \
    (0u COMPANION_GATT_SERVICE_SCHEMA(COMPANION_SERVICE_ATTRIBUTE_RESERVATION))

/* ST value-array rule for128-bit characteristic UUIDs; node storage is
 * counted separately by ble_bufsize.h. Schema growth updates this budget. */
#define COMPANION_COUNT_VALUE_BYTES(id,uuid,size,props,events,variable) \
    + ((size) + 19u + (((props)&0x01u)?2u:0u) + \
       (((props)&0x30u)?2u:0u) + (((props)&0x80u)?2u:0u))
#define COMPANION_SERVICE_VALUE_BYTES(uuid,records,count,chars) \
    + (0u chars##_SCHEMA(COMPANION_COUNT_VALUE_BYTES))
#define COMPANION_GATT_PRODUCT_VALUE_BYTES \
    (0u COMPANION_GATT_SERVICE_SCHEMA(COMPANION_SERVICE_VALUE_BYTES))

#endif
