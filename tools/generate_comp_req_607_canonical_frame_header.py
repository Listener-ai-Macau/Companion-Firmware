#!/usr/bin/env python3
"""Bind the COMP-REQ-607 lower runner to the already accepted frame plan.

This generator is deliberately strict: it will not produce a C header when
the canonical JSON, payload container, offsets, order, or per-frame hashes do
not match the owner-approved identity.
"""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path


CANONICAL_JSON_SHA256 = (
    "5F4A5AC88EBCC166E94BD8A4797DE4BB5C111297AE9CFEAE889755ACF6BA4754"
)
CANONICAL_BIN_SHA256 = (
    "6979C9591879A95C73032384A85C0C4564FA3D405BC92B892D802BA9A62FF188"
)
PAGE_SHA256 = "307744ABAE5BE52F35491DBCACA5BC3D0544306733A3347F48C6C7990351B58D"
FRAME_COUNT = 56
FRAME_BYTES = 5000
CADENCE_MS = 480


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest().upper()


def fail(message: str) -> None:
    raise SystemExit(f"COMP-REQ-607 canonical input rejected: {message}")


def validate(json_path: Path, bin_path: Path) -> tuple[dict, bytes, list[dict]]:
    json_bytes = json_path.read_bytes()
    payload = bin_path.read_bytes()
    json_sha = sha256(json_bytes)
    bin_sha = sha256(payload)
    if json_sha != CANONICAL_JSON_SHA256:
        fail(f"plan_sha256={json_sha} expected={CANONICAL_JSON_SHA256}")
    if bin_sha != CANONICAL_BIN_SHA256:
        fail(f"payload_sha256={bin_sha} expected={CANONICAL_BIN_SHA256}")
    plan = json.loads(json_bytes.decode("utf-8"))
    entries = plan.get("entries")
    if not isinstance(entries, list) or len(entries) != FRAME_COUNT:
        fail(f"entry_count={len(entries) if isinstance(entries, list) else 'invalid'}")
    if plan.get("width") != 200 or plan.get("height") != 200:
        fail("frame dimensions are not 200x200")
    if plan.get("bytes_per_frame") != FRAME_BYTES:
        fail("bytes_per_frame is not 5000")
    if plan.get("cadence_ms") != CADENCE_MS:
        fail("cadence_ms is not 480")
    if len(payload) != FRAME_COUNT * FRAME_BYTES:
        fail(f"payload_length={len(payload)}")

    for index, entry in enumerate(entries):
        expected_offset = index * FRAME_BYTES
        offset = entry.get("payload_offset")
        if offset != expected_offset:
            fail(f"frame={index} offset={offset} expected={expected_offset}")
        if entry.get("payload_bytes") != FRAME_BYTES:
            fail(f"frame={index} payload_bytes is not 5000")
        if entry.get("cadence_ms") != CADENCE_MS:
            fail(f"frame={index} cadence is not 480")
        if entry.get("dwell_commits") != 1:
            fail(f"frame={index} dwell_commits is not 1")
        frame = payload[offset : offset + FRAME_BYTES]
        frame_sha = sha256(frame)
        if frame_sha != entry.get("framebuffer_sha256", "").upper():
            fail(f"frame={index} hash does not match plan")
    return plan, payload, entries


def c_bytes(frame: bytes) -> str:
    rows = []
    for start in range(0, len(frame), 16):
        row = ", ".join(f"0x{value:02X}u" for value in frame[start : start + 16])
        rows.append(f"    {row},")
    return "\n".join(rows)


def write_header(path: Path, payload: bytes, entries: list[dict]) -> None:
    frames = [payload[i * FRAME_BYTES : (i + 1) * FRAME_BYTES] for i in range(FRAME_COUNT)]
    with path.open("w", encoding="ascii", newline="\n") as stream:
        stream.write("/* Generated by generate_comp_req_607_canonical_frame_header.py. */\n")
        stream.write("#ifndef COMP_REQ_607_CANONICAL_FRAMES_H\n#define COMP_REQ_607_CANONICAL_FRAMES_H\n\n")
        stream.write("#include <stdint.h>\n\n")
        stream.write("#define COMP_REQ_607_FRAME_COUNT 56u\n")
        stream.write("#define COMP_REQ_607_FRAME_BYTES 5000u\n")
        stream.write("#define COMP_REQ_607_FRAME_CADENCE_MS 480u\n\n")
        stream.write("static const char *const comp_req_607_frame_sha256[COMP_REQ_607_FRAME_COUNT] = {\n")
        for entry in entries:
            stream.write(f'    "{entry["framebuffer_sha256"].upper()}",\n')
        stream.write("};\n\n")
        stream.write("static const char *const comp_req_607_frame_ids[COMP_REQ_607_FRAME_COUNT] = {\n")
        for entry in entries:
            stream.write(f'    "{entry["id"]}",\n')
        stream.write("};\n\n")
        stream.write("static const uint8_t comp_req_607_canonical_frames[COMP_REQ_607_FRAME_COUNT][COMP_REQ_607_FRAME_BYTES] = {\n")
        for index, frame in enumerate(frames):
            stream.write(f"    /* {index}: {entries[index]['id']} */\n    {{\n")
            stream.write(c_bytes(frame))
            stream.write("\n    },\n")
        stream.write("};\n\n#endif\n")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--payload", type=Path, required=True)
    parser.add_argument("--header", type=Path, required=True)
    parser.add_argument("--evidence", type=Path, required=True)
    args = parser.parse_args()

    plan, payload, entries = validate(args.plan, args.payload)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.evidence.parent.mkdir(parents=True, exist_ok=True)
    write_header(args.header, payload, entries)
    evidence = {
        "schema": "companion.comp_req_607.lower_canonical_sync.v1",
        "requirement": "COMP-REQ-607",
        "page_sha256": PAGE_SHA256,
        "canonical_plan_path": str(args.plan),
        "canonical_plan_sha256": CANONICAL_JSON_SHA256,
        "canonical_payload_path": str(args.payload),
        "canonical_payload_sha256": CANONICAL_BIN_SHA256,
        "frame_count": FRAME_COUNT,
        "frame_bytes": FRAME_BYTES,
        "payload_bytes": len(payload),
        "cadence_ms": CADENCE_MS,
        "dwell_commits": [entry["dwell_commits"] for entry in entries],
        "ordered_frame_ids": [entry["id"] for entry in entries],
        "frame_sha256": [entry["framebuffer_sha256"].upper() for entry in entries],
        "generated_header_sha256": sha256(args.header.read_bytes()),
    }
    args.evidence.write_text(json.dumps(evidence, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(evidence, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
