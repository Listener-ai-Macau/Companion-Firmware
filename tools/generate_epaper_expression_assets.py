#!/usr/bin/env python3
"""Generate portable 200x200 ExpressionV1 C assets from approved PBM fixtures."""

from __future__ import annotations

import argparse
import pathlib
import sys


REPO_ROOT = pathlib.Path(__file__).resolve().parents[1]
FIXTURE_DIR = REPO_ROOT / "docs" / "validation" / "epaper"
DEFAULT_OUTPUT = REPO_ROOT / "app" / "companion_pendant" / "epaper" / "expression_assets_200x200.c"
WIDTH = 200
HEIGHT = 200
FRAME_BYTES = (WIDTH // 8) * HEIGHT
ASSETS = (
    ("idle", "COMP_EPAPER_EXPRESSION_IDLE"),
    ("listening", "COMP_EPAPER_EXPRESSION_LISTENING"),
    ("thinking", "COMP_EPAPER_EXPRESSION_THINKING"),
    ("speaking", "COMP_EPAPER_EXPRESSION_SPEAKING"),
    ("happy", "COMP_EPAPER_EXPRESSION_HAPPY"),
    ("sleepy", "COMP_EPAPER_EXPRESSION_SLEEPY"),
    ("recording", "COMP_EPAPER_EXPRESSION_RECORDING"),
    ("sync_complete", "COMP_EPAPER_EXPRESSION_SYNC_COMPLETE"),
    ("low_battery", "COMP_EPAPER_EXPRESSION_LOW_BATTERY"),
    ("error", "COMP_EPAPER_EXPRESSION_ERROR"),
)


def parse_p4(path: pathlib.Path) -> bytes:
    data = path.read_bytes()
    index = 0
    tokens: list[bytes] = []

    while len(tokens) < 3:
        while index < len(data) and data[index:index + 1] in b" \t\r\n":
            index += 1
        if index < len(data) and data[index:index + 1] == b"#":
            while index < len(data) and data[index:index + 1] not in b"\r\n":
                index += 1
            continue
        start = index
        while index < len(data) and data[index:index + 1] not in b" \t\r\n":
            index += 1
        if start == index:
            raise ValueError(f"{path}: missing PBM header token")
        tokens.append(data[start:index])

    if tokens[0] != b"P4":
        raise ValueError(f"{path}: expected P4 PBM fixture")
    if (int(tokens[1]), int(tokens[2])) != (WIDTH, HEIGHT):
        raise ValueError(f"{path}: expected {WIDTH}x{HEIGHT} PBM fixture")

    if data[index:index + 2] == b"\r\n":
        index += 2
    elif data[index:index + 1] in b" \t\r\n":
        index += 1
    else:
        raise ValueError(f"{path}: missing PBM payload separator")

    payload = data[index:index + FRAME_BYTES]
    if len(payload) != FRAME_BYTES:
        raise ValueError(f"{path}: expected {FRAME_BYTES} payload bytes, found {len(payload)}")
    return bytes(byte ^ 0xFF for byte in payload)


def format_array(name: str, payload: bytes) -> list[str]:
    lines = [f"static const uint8_t s_expression_{name}[COMPANION_EPAPER_EXPRESSION_ASSET_BYTES] = {{"]
    for start in range(0, len(payload), 16):
        values = ", ".join(f"0x{byte:02X}u" for byte in payload[start:start + 16])
        lines.append(f"    {values},")
    lines.append("};")
    lines.append("")
    return lines


def render_source() -> str:
    payloads: list[tuple[str, str, bytes]] = []
    for name, expression in ASSETS:
        path = FIXTURE_DIR / f"expression_{name}_1_54in.pbm"
        payloads.append((name, expression, parse_p4(path)))

    lines = [
        "/* Generated by tools/generate_epaper_expression_assets.py. Do not edit manually. */",
        "#include \"expression_assets_200x200.h\"",
        "",
        "#include <string.h>",
        "",
    ]
    for name, _expression, payload in payloads:
        lines.extend(format_array(name, payload))
    lines.extend(
        [
            "static const uint8_t *const s_expression_assets[COMP_EPAPER_EXPRESSION_COUNT] = {",
        ]
    )
    for name, expression, _payload in payloads:
        lines.append(f"    [{expression}] = s_expression_{name},")
    lines.extend(
        [
            "};",
            "",
            "bool companion_epaper_expression_asset_200x200_copy(",
            "    comp_epaper_expression_t expression,",
            "    uint8_t *out_frame,",
            "    size_t out_frame_size)",
            "{",
            "    if (out_frame == NULL || out_frame_size != COMPANION_EPAPER_EXPRESSION_ASSET_BYTES ||",
            "        expression >= COMP_EPAPER_EXPRESSION_COUNT ||",
            "        s_expression_assets[expression] == NULL) {",
            "        return false;",
            "    }",
            "",
            "    memcpy(out_frame, s_expression_assets[expression], COMPANION_EPAPER_EXPRESSION_ASSET_BYTES);",
            "    return true;",
            "}",
            "",
        ]
    )
    return "\n".join(lines)


def parse_args(argv: list[str]) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=pathlib.Path, default=DEFAULT_OUTPUT)
    parser.add_argument("--write", action="store_true", help="write the generated C source")
    parser.add_argument("--check", action="store_true", help="fail if the generated C source is stale")
    return parser.parse_args(argv)


def main(argv: list[str]) -> int:
    args = parse_args(argv)
    if args.write == args.check:
        raise SystemExit("choose exactly one of --write or --check")

    expected = render_source()
    output = args.output.resolve()
    if args.check:
        actual = output.read_text(encoding="ascii") if output.exists() else ""
        if actual != expected:
            print(f"FAIL: ExpressionV1 C assets are stale -> {output}")
            return 1
        print(f"PASS: ExpressionV1 C assets match approved 200x200 PBM fixtures -> {output}")
        return 0

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text(expected, encoding="ascii", newline="\n")
    print(f"PASS: generated ExpressionV1 C assets from {len(ASSETS)} approved PBM fixtures -> {output}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
