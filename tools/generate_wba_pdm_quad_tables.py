"""Exact byte contributions propagated through16/24 additional PDM clocks."""
from pathlib import Path
import sys

DEST=Path(__file__).resolve().parents[1]/'app/companion_pendant/recording/wba_pdm_quad_tables.h'
def contribution(byte,following):
    one=two=three=0
    for bit in range(7,-1,-1):
        one+=1 if byte&(1<<bit)else -1
        two+=one;three+=two
    return one,two+following*one,three+following*two+following*(following+1)//2*one

def render():
    lines=['/* Generated by tools/generate_wba_pdm_quad_tables.py. Exact CIC3',
           ' * contributions, signed fields a[4:0],b[13:5],c[26:14]. No RAM. */',
           '#ifndef COMPANION_WBA_PDM_QUAD_TABLES_H',
           '#define COMPANION_WBA_PDM_QUAD_TABLES_H']
    for following in [24,16]:
        values=[]
        for byte in range(256):
            a,b,c=contribution(byte,following)
            assert -16<=a<16 and -256<=b<256 and -4096<=c<4096
            values.append((a&31)|((b&511)<<5)|((c&8191)<<14))
        lines.append('static const uint32_t byte_sums_forward'+str(following)+'[256] = {')
        lines += ['    '+', '.join(f'0x{n:08X}u'for n in values[i:i+8])+','for i in range(0,256,8)]
        lines.append('};')
    return '\n'.join(lines+['#endif',''])

if __name__=='__main__':
    output=render()
    if '--check' in sys.argv:
        assert DEST.read_text()==output
        print('PASS_EXACT_GENERATED_CIC3_QUAD_TABLES')
    else:
        DEST.write_text(output,encoding='utf-8',newline='\n')
