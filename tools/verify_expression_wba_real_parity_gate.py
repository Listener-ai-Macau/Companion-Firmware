#!/usr/bin/env python3
"""Verify WBA real-panel parity cannot be claimed from pre-port evidence."""

from __future__ import annotations

import argparse
import json
import pathlib
import sys
from typing import Any


ROOT = pathlib.Path(__file__).resolve().parents[1]
DEFAULT_JSON = ROOT / "docs/validation/companion-screen-wba-real-parity-gate.json"
WBA_PORT = ROOT / "docs/validation/companion-screen-wba-port-contract.json"
WBA_SCAFFOLD = ROOT / "docs/validation/companion-screen-wba55-port-scaffold.json"
CUBE_PREFLIGHT = ROOT / "docs/validation/companion-screen-wba-cube-dependency-preflight.json"
PANEL_TARGET = ROOT / "docs/validation/companion-screen-panel-target-stm32wba.json"
TOUCH_TARGET = ROOT / "docs/validation/companion-screen-touch-ft6336-stm32wba.json"
REAL_BLE_BENCH = ROOT / "docs/validation/companion-screen-real-ble-bench.json"
PANEL_SESSION = ROOT / "docs/validation/companion-screen-panel-hardware-session.json"
WBA_RULES = ROOT / "docs/stm32wba_migration_rules.md"
WBA_LSE_CLOCK = ROOT / "docs/validation/companion-screen-wba-lse-clock-contract.json"
SCHEMA_ID = "companion.pendant.screen_wba_real_parity_gate.v1"


def rel(path: pathlib.Path) -> str:
    return path.resolve().relative_to(ROOT).as_posix()


def load_json(path: pathlib.Path) -> dict[str, Any]:
    return json.loads(path.read_text(encoding="utf-8"))


def require(condition: bool, message: str, errors: list[str]) -> None:
    if not condition:
        errors.append(message)


def source(path: pathlib.Path, summary: str) -> dict[str, str]:
    return {"path": rel(path), "summary": summary}


def build_gate() -> dict[str, Any]:
    port = load_json(WBA_PORT)
    scaffold = load_json(WBA_SCAFFOLD)
    cube = load_json(CUBE_PREFLIGHT)
    panel = load_json(PANEL_TARGET)
    touch = load_json(TOUCH_TARGET)
    real_ble = load_json(REAL_BLE_BENCH)
    panel_session = load_json(PANEL_SESSION)
    lse_clock = load_json(WBA_LSE_CLOCK)

    target_evidence_requirements = {
        "exact_target_identity": (
            "Every WBA promotion artifact must declare target_family=STM32WBA "
            "and exact_target=WBA55 or WBA65; target-neutral, WB55, or scaffold-only "
            "evidence is not enough."
        ),
        "target_named_paths": (
            "WBA build logs, BLE captures, panel evidence records, touch logs, and "
            "visual evidence must live under target-named WBA55/WBA65 paths or carry "
            "target-named metadata generated by the WBA build/bench wrapper."
        ),
        "no_wb55_substitution": (
            "WB55 runtime logs, WB55 build logs, NUCLEO-WB55RG wiring, WB55 photos, "
            "and panel_target_stm32wb evidence may be cited only as baseline history; "
            "they must never satisfy a WBA promotion requirement."
        ),
        "adapter_identity": (
            "WBA evidence must name *_stm32wba.* adapters for panel, scheduler, GATT, "
            "assets, and touch; *_stm32wb.* adapters are allowed only in the baseline "
            "comparison section."
        ),
    }

    missing_or_deferred = [
        {
            "id": "cube_wba_dependency",
            "status": "missing",
            "evidence": rel(CUBE_PREFLIGHT),
            "reason": "third_party/STM32CubeWBA is not present, so no separate CubeWBA project/build can be claimed.",
        },
        {
            "id": "cube_wba_project",
            "status": "todo",
            "evidence": rel(WBA_SCAFFOLD),
            "reason": "WBA scaffold still contains TODO_CUBEWBA_PROJECT_PATH_FOR_WBA55.",
        },
        {
            "id": "wba_build_wrapper",
            "status": "todo",
            "evidence": rel(WBA_SCAFFOLD),
            "reason": "WBA scaffold still contains TODO_WBA_BUILD_WRAPPER_FOR_WBA55.",
        },
        {
            "id": "real_ble_expect_panel_artifact",
            "status": "todo",
            "evidence": rel(WBA_SCAFFOLD),
            "reason": "No WBA --expect-real-panel bench artifact exists for screen_expression_status, card_write, and settings_sleepy_screen_status.",
        },
        {
            "id": "filled_wba_panel_evidence_record",
            "status": "todo",
            "evidence": rel(WBA_SCAFFOLD),
            "reason": "WBA panel evidence record is only a scaffold path until real controller, pins, timing, logs, and visual evidence are filled.",
        },
        {
            "id": "wba_touch_hardware_parity",
            "status": "deferred",
            "evidence": rel(TOUCH_TARGET),
            "reason": "WBA FT6336 scaffold has callback shape only; real address, identity, corners, and gestures are still required.",
        },
        {
            "id": "wba_lse_clock_hardware_evidence",
            "status": "deferred",
            "evidence": rel(WBA_LSE_CLOCK),
            "reason": "WBA LSE contract is recorded, but real LSE startup, RTC continuity, BLE sleep/connection, and timed wake-up evidence do not exist yet.",
        },
    ]

    return {
        "schema_id": SCHEMA_ID,
        "status": "PASS_PRE_PORT_PARITY_BLOCKED",
        "purpose": "Prevent a WBA55/WBA65 screen parity claim from WB55 evidence or scaffold-only WBA adapters.",
        "parity_claim_allowed": False,
        "blocked_gate": port.get("blocked_until_hardware", {}).get("gate"),
        "blocked_reason": port.get("blocked_until_hardware", {}).get("reason"),
        "current_state": {
            "wba_port_scaffold_status": scaffold.get("status"),
            "cube_wba_mode": cube.get("local_state", {}).get("mode"),
            "stm32cubewba_present": cube.get("local_state", {}).get("stm32cubewba_present"),
            "cube_preflight_allows_parity": cube.get("contract", {}).get("wba_parity_claim_allowed"),
            "panel_target_real_refresh_claimed": panel.get("contract", {}).get("real_refresh_claimed"),
            "touch_target_hardware_parity_claimed": touch.get("contract", {}).get("hardware_parity_claimed"),
            "real_ble_contract_requires_expect_panel": (
                real_ble.get("bench_operation", {}).get("real_panel_flag") == "--expect-real-panel"
                and real_ble.get("expression_bench_operation", {}).get("real_panel_flag") == "--expect-real-panel"
            ),
            "lse_clock_contract_status": lse_clock.get("status"),
            "lse_clock_hardware_claimed": lse_clock.get("current_state", {}).get("hardware_claimed"),
        },
        "sources": [
            source(WBA_PORT, "portable WBA pre-port contract and blocked hardware gate"),
            source(WBA_SCAFFOLD, "target-specific WBA55 first-port artifact checklist"),
            source(CUBE_PREFLIGHT, "local CubeWBA dependency state"),
            source(PANEL_TARGET, "WBA panel target scaffold real-refresh status"),
            source(TOUCH_TARGET, "WBA FT6336 target scaffold hardware-parity status"),
            source(REAL_BLE_BENCH, "real BLE screen bench --expect-real-panel contract"),
            source(PANEL_SESSION, "WB55/WBA55/WBA65 panel session command scaffold"),
            source(WBA_LSE_CLOCK, "WBA LSE/RTC/BLE sleep clock contract"),
            source(WBA_RULES, "human-readable WBA migration rules"),
        ],
        "target_evidence_requirements": target_evidence_requirements,
        "missing_or_deferred_evidence": missing_or_deferred,
        "promotion_requirements": [
            "Add or document the STM32CubeWBA upstream dependency.",
            "Create a separate CubeWBA IOC/project for WBA55 or WBA65.",
            "Add a scriptable WBA build wrapper; do not retarget the WB55 Cube project in place.",
            "Wire WBA BLE/GATT through screen_gatt_stm32wba and preserve CardStatusV1 identity.",
            "Wire WBA scheduler/time through screen_scheduler_stm32wba and preserve display drain.",
            "Wire WBA external UI assets through screen_assets_stm32wba with a real partition readback.",
            "Wire WBA panel transport through panel_target_stm32wba and comp_epaper_panel_refresh_fn_t.",
            "Capture a real BLE artifact with --expect-real-panel including screen_expression_status, card_write, and settings_sleepy_screen_status.",
            "Fill and pass a WBA panel evidence record with runtime diagnostics and before/during/after visual evidence.",
            "Capture WBA FT6336 address, identity, corner-coordinate, and gesture evidence before touch parity is claimed.",
            "Prove WBA LSE startup, RTC continuity across sleep, BLE advertising/connection through sleep, and timed wake-up, or record an explicit no-LSE radio-clock/power exception.",
            "Ensure every WBA promotion artifact declares target_family=STM32WBA and exact_target=WBA55 or WBA65.",
            "Reject WB55 runtime/build/visual/wiring evidence as WBA promotion evidence; it is baseline history only.",
        ],
        "validation_commands": [
            "python .\\tools\\verify_expression_wba_real_parity_gate.py",
            "python .\\tools\\verify_expression_wba_cube_dependency_preflight.py",
            "python .\\tools\\init_expression_wba_port_scaffold.py",
            "python .\\tools\\verify_expression_panel_target_stm32wba.py",
            "python .\\tools\\verify_touch_target_stm32wba_ft6336.py",
            "python .\\tools\\verify_expression_real_ble_screen_bench.py",
            "python .\\tools\\verify_expression_panel_evidence_record.py --self-test",
            "python .\\tools\\verify_expression_wba_lse_clock_contract.py",
        ],
    }


def check_gate(gate: dict[str, Any], errors: list[str]) -> None:
    require(gate.get("schema_id") == SCHEMA_ID, "unexpected schema_id", errors)
    require(gate.get("status") == "PASS_PRE_PORT_PARITY_BLOCKED", "gate status must remain pre-port blocked", errors)
    require(gate.get("parity_claim_allowed") is False, "WBA parity must not be claimable", errors)
    require(gate.get("blocked_gate") == "wba_real_panel_refresh", "blocked gate must be wba_real_panel_refresh", errors)

    state = gate.get("current_state", {})
    require(state.get("wba_port_scaffold_status") == "DRAFT_PRE_PORT", "WBA scaffold must stay DRAFT_PRE_PORT", errors)
    require(state.get("cube_wba_mode") == "missing_upstream_reference", "CubeWBA preflight mode drifted", errors)
    require(state.get("stm32cubewba_present") is False, "STM32CubeWBA should not be recorded present yet", errors)
    require(state.get("cube_preflight_allows_parity") is False, "Cube preflight must not allow WBA parity", errors)
    require(state.get("panel_target_real_refresh_claimed") is False, "WBA panel target must not claim real refresh", errors)
    require(state.get("touch_target_hardware_parity_claimed") is False, "WBA touch target must not claim hardware parity", errors)
    require(state.get("real_ble_contract_requires_expect_panel") is True, "real BLE contract must require --expect-real-panel", errors)
    require(state.get("lse_clock_contract_status") == "PASS_PRE_PORT_CLOCK_CONTRACT_RECORDED", "WBA LSE clock contract must be recorded", errors)
    require(state.get("lse_clock_hardware_claimed") is False, "WBA LSE clock hardware must not be claimed pre-port", errors)

    target_rules = gate.get("target_evidence_requirements", {})
    for required in (
        "exact_target_identity",
        "target_named_paths",
        "no_wb55_substitution",
        "adapter_identity",
    ):
        require(required in target_rules, f"missing target evidence rule {required}", errors)

    missing_ids = {item.get("id") for item in gate.get("missing_or_deferred_evidence", [])}
    for required in (
        "cube_wba_dependency",
        "cube_wba_project",
        "wba_build_wrapper",
        "real_ble_expect_panel_artifact",
        "filled_wba_panel_evidence_record",
        "wba_touch_hardware_parity",
        "wba_lse_clock_hardware_evidence",
    ):
        require(required in missing_ids, f"missing evidence item {required}", errors)

    serialized = json.dumps(gate, ensure_ascii=False)
    for token in (
        "TODO_CUBEWBA_PROJECT_PATH_FOR_WBA55",
        "TODO_WBA_BUILD_WRAPPER_FOR_WBA55",
        "--expect-real-panel",
        "screen_expression_status",
        "card_write",
        "settings_sleepy_screen_status",
        "verify_expression_panel_evidence_record.py --self-test",
        "comp_epaper_panel_refresh_fn_t",
        "target_family=STM32WBA",
        "exact_target=WBA55 or WBA65",
        "target-named WBA55/WBA65 paths",
        "NUCLEO-WB55RG wiring",
        "panel_target_stm32wb evidence may be cited only as baseline history",
        "*_stm32wba.* adapters",
        "Reject WB55 runtime/build/visual/wiring evidence as WBA promotion evidence",
        "LSE startup",
        "RTC continuity across sleep",
        "BLE advertising/connection through sleep",
        "no-LSE radio-clock/power exception",
        "verify_expression_wba_lse_clock_contract.py",
    ):
        require(token in serialized, f"gate missing token {token}", errors)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--json", type=pathlib.Path, default=DEFAULT_JSON)
    args = parser.parse_args(argv)

    json_path = args.json if args.json.is_absolute() else ROOT / args.json
    gate = build_gate()
    errors: list[str] = []
    check_gate(gate, errors)
    rendered = json.dumps(gate, indent=2, ensure_ascii=False, sort_keys=True) + "\n"

    if args.write:
        json_path.write_text(rendered, encoding="utf-8")
    else:
        if not json_path.exists():
            errors.append(f"missing {rel(json_path)}")
        elif json_path.read_text(encoding="utf-8") != rendered:
            errors.append(f"{rel(json_path)} is stale; rerun with --write")

    if errors:
        print("FAIL: WBA real parity gate checks failed:", file=sys.stderr)
        for error in errors:
            print(f" - {error}", file=sys.stderr)
        return 1
    print(f"PASS: WBA real parity gate verified -> {rel(json_path)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
